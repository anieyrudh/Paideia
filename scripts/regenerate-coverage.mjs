#!/usr/bin/env node
/**
 * regenerate-coverage.mjs
 *
 * Walks every container and rewrites docs/_meta/coverage.md as a markdown
 * table of: branch | subject | concept (package id) | status.
 *
 * The status is read from the `status:` field at the root of each
 * concept-package.yaml.
 *
 * Used by .github/workflows/daily-coverage-report.yml.
 *
 * No external dependencies — uses only Node built-ins. The status field is
 * read with a small regex (good enough for the canonical YAML shape produced
 * by the scaffolder). If the YAML is malformed, the row is written with
 * status `unknown`.
 *
 * Exit codes:
 *   0 — coverage table written (or rewritten in place; no-op is fine)
 *   1 — IO failure
 */

import {
  readdirSync,
  readFileSync,
  statSync,
  existsSync,
  mkdirSync,
  writeFileSync
} from "node:fs";
import { join, resolve, dirname } from "node:path";

const REPO_ROOT = resolve(process.cwd());
const BRANCHES = ["a-level", "sutd"];
const OUTPUT_PATH = join(REPO_ROOT, "docs", "_meta", "coverage.md");

function readStatus(yamlPath) {
  try {
    const raw = readFileSync(yamlPath, "utf8");
    const match = raw.match(/^status\s*:\s*['"]?([A-Za-z0-9_-]+)['"]?/m);
    return match ? match[1] : "unknown";
  } catch {
    return "unknown";
  }
}

function readId(yamlPath, fallback) {
  try {
    const raw = readFileSync(yamlPath, "utf8");
    const match = raw.match(/^id\s*:\s*['"]?([A-Za-z0-9._/-]+)['"]?/m);
    return match ? match[1] : fallback;
  } catch {
    return fallback;
  }
}

function walk() {
  const rows = [];
  for (const branch of BRANCHES) {
    const contentDir = join(REPO_ROOT, branch, "content");
    if (!existsSync(contentDir) || !statSync(contentDir).isDirectory()) continue;
    for (const subject of readdirSync(contentDir)) {
      const subjectDir = join(contentDir, subject);
      if (!statSync(subjectDir).isDirectory()) continue;
      const packagesDir = join(subjectDir, "concept-packages");
      if (!existsSync(packagesDir) || !statSync(packagesDir).isDirectory()) continue;
      for (const pkg of readdirSync(packagesDir)) {
        const pkgDir = join(packagesDir, pkg);
        if (!statSync(pkgDir).isDirectory()) continue;
        const yamlPath = join(pkgDir, "concept-package.yaml");
        const status = existsSync(yamlPath) ? readStatus(yamlPath) : "missing-yaml";
        const id = existsSync(yamlPath) ? readId(yamlPath, pkg) : pkg;
        rows.push({ branch, subject, concept: id, status });
      }
    }
  }
  // Sort: branch, subject, concept
  rows.sort((a, b) => {
    if (a.branch !== b.branch) return a.branch < b.branch ? -1 : 1;
    if (a.subject !== b.subject) return a.subject < b.subject ? -1 : 1;
    return a.concept < b.concept ? -1 : 1;
  });
  return rows;
}

function render(rows) {
  const lines = [
    "# Container coverage",
    "",
    "_Auto-generated by `scripts/regenerate-coverage.mjs`. Do not edit by hand — this file is overwritten by the `daily-coverage-report.yml` workflow each day at 18:00 SGT._",
    "",
    `_Last generated (UTC): ${new Date().toISOString()}_`,
    "",
    "| Branch | Subject | Concept | Status |",
    "| --- | --- | --- | --- |"
  ];

  if (rows.length === 0) {
    lines.push("| _(none)_ | | | |");
  } else {
    for (const r of rows) {
      lines.push(`| \`${r.branch}\` | \`${r.subject}\` | \`${r.concept}\` | \`${r.status}\` |`);
    }
  }

  // Summary counts by status
  const byStatus = new Map();
  for (const r of rows) {
    byStatus.set(r.status, (byStatus.get(r.status) || 0) + 1);
  }
  lines.push("");
  lines.push("## Totals by status");
  lines.push("");
  if (byStatus.size === 0) {
    lines.push("_(no containers)_");
  } else {
    lines.push("| Status | Count |");
    lines.push("| --- | --- |");
    for (const [status, count] of [...byStatus.entries()].sort()) {
      lines.push(`| \`${status}\` | ${count} |`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

function main() {
  const rows = walk();
  const content = render(rows);

  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });

  // Only write if content has actually changed — the create-pull-request action
  // is a no-op if the diff is empty, but avoiding the write keeps mtimes clean.
  let existing = "";
  if (existsSync(OUTPUT_PATH)) {
    try {
      existing = readFileSync(OUTPUT_PATH, "utf8");
    } catch {
      existing = "";
    }
  }
  if (existing === content) {
    process.stdout.write("regenerate-coverage: no change.\n");
    process.exit(0);
  }
  writeFileSync(OUTPUT_PATH, content, "utf8");
  process.stdout.write(
    `regenerate-coverage: wrote ${OUTPUT_PATH} (${rows.length} container(s)).\n`
  );
  process.exit(0);
}

main();

#!/usr/bin/env node
/**
 * Generate branch app catalogue data from validated ConceptPackage manifests.
 *
 * v0 targets:
 *   a-level/content/.../concept-package.yaml -> a-level/apps/shell/src/generated/catalogue.tsx
 *   sutd/content/.../concept-package.yaml -> sutd/apps/shell/src/generated/catalogue.tsx
 *
 * A target is skipped until its app directory exists.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, join, relative, resolve } from "node:path";
import YAML from "yaml";

const REPO_ROOT = resolve(process.cwd());
const TARGETS = [
  {
    branch: "a-level",
    appDir: join(REPO_ROOT, "a-level", "apps", "shell"),
    output: join(REPO_ROOT, "a-level", "apps", "shell", "src", "generated", "catalogue.tsx"),
  },
  {
    branch: "sutd",
    appDir: join(REPO_ROOT, "sutd", "apps", "shell"),
    output: join(REPO_ROOT, "sutd", "apps", "shell", "src", "generated", "catalogue.tsx"),
  },
];

const isDirectory = (path) => existsSync(path) && statSync(path).isDirectory();

const readYaml = (path) => YAML.parse(readFileSync(path, "utf8"));

const findConceptPackages = (branch) => {
  const contentDir = join(REPO_ROOT, branch, "content");
  if (!existsSync(contentDir)) return [];

  const manifests = [];
  for (const subject of readdirSync(contentDir)) {
    const packagesDir = join(contentDir, subject, "concept-packages");
    if (!existsSync(packagesDir)) continue;

    for (const packageId of readdirSync(packagesDir)) {
      const manifestPath = join(packagesDir, packageId, "concept-package.yaml");
      if (existsSync(manifestPath)) manifests.push(manifestPath);
    }
  }

  return manifests.sort();
};

const toIdentifier = (value, index) => {
  const suffix = value
    .replace(/[^a-zA-Z0-9]+/g, " ")
    .trim()
    .split(/\s+/g)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
  return `GeneratedSim${index}${suffix}`;
};

const jsString = (value) => JSON.stringify(value);

const renderArray = (items, indent = "      ") =>
  items.length === 0
    ? "[]"
    : `[\n${items.map((item) => `${indent}${jsString(item)},`).join("\n")}\n${indent.slice(0, -2)}]`;

const firstRendererModule = (sim, manifestPath) => {
  const module = sim.observe?.renderers?.[0]?.module;
  if (typeof module !== "string" || module.length === 0) {
    throw new Error(`${relative(REPO_ROOT, manifestPath)} sim ${sim.id} has no renderer module`);
  }
  return module;
};

const renderCatalogue = (branch, manifests) => {
  const imports = [];
  const containers = [];
  let importIndex = 0;

  for (const manifestPath of manifests) {
    const manifest = readYaml(manifestPath);
    const packageId = basename(manifestPath.replace(/\/concept-package\.yaml$/u, ""));
    const subject = manifest.subject;
    const sims = [];

    for (const sim of manifest.items?.sims ?? []) {
      const importName = toIdentifier(`${manifest.id}-${sim.id}`, importIndex);
      const moduleName = firstRendererModule(sim, manifestPath);
      importIndex += 1;
      imports.push(`import ${importName} from ${jsString(moduleName)};`);
      sims.push(`      {
        id: ${jsString(sim.id)},
        title: ${jsString(sim.title)},
        interactionType: ${jsString(sim.interaction_type)},
        component: ${importName},
      }`);
    }

    if (sims.length === 0) continue;

    const predictPrompt = manifest.package_predict?.prompt ?? manifest.items.sims[0]?.predict?.prompt ?? "";
    const misconceptions = (manifest.misconceptions ?? []).map((entry) => entry.name);
    const transferProblem =
      manifest.items?.transfer_problems?.[0]?.prompt === undefined
        ? "No transfer problem registered yet."
        : manifest.items.transfer_problems[0].prompt.trim();

    containers.push(`  {
    id: ${jsString(`${branch}/${subject}/${manifest.id}`)},
    branch: ${jsString(branch)},
    subject: ${jsString(subject)},
    subjectLabel: ${jsString(subject.replace(/-/gu, " ").replace(/\b\w/gu, (match) => match.toUpperCase()))},
    level: ${jsString(manifest.level ?? "")},
    title: ${jsString(manifest.title)},
    summary: ${jsString(manifest.one_line_summary)},
    syllabusRef: ${jsString(manifest.syllabus_ref ?? "")},
    status: ${jsString(manifest.status)},
    packageId: ${jsString(packageId)},
    simId: ${jsString(manifest.items.sims[0]?.id ?? "package")},
    predictPrompt: ${jsString(predictPrompt.trim())},
    aidTypes: ${renderArray(manifest.aid_types ?? [], "      ")},
    misconceptions: ${renderArray(misconceptions, "      ")},
    transferProblem: ${jsString(transferProblem)},
    sims: [
${sims.join(",\n")}
    ],
  }`);
  }

  if (containers.length === 0) {
    throw new Error(`No runnable sims found for ${branch}`);
  }

  return `// Auto-generated by scripts/generate-catalogue.mjs. Do not edit by hand.
import type { ShellContainer } from "../catalogue-types.js";
${imports.join("\n")}

export const containers = [
${containers.join(",\n")}
] satisfies readonly [ShellContainer, ...ShellContainer[]];
`;
};

for (const target of TARGETS) {
  if (!existsSync(target.appDir)) continue;
  if (!isDirectory(target.appDir)) continue;

  const manifests = findConceptPackages(target.branch);
  const output = renderCatalogue(target.branch, manifests);
  mkdirSync(resolve(target.output, ".."), { recursive: true });
  writeFileSync(target.output, output, "utf8");
  process.stdout.write(
    `generate-catalogue: wrote ${relative(REPO_ROOT, target.output)} from ${manifests.length} container(s)\n`,
  );
}
